package com.example.data

import android.content.Context
import android.content.Intent
import android.util.Log
import com.example.BuildConfig
import com.google.firebase.FirebaseApp
import com.google.firebase.appcheck.FirebaseAppCheck
import com.google.firebase.appcheck.debug.DebugAppCheckProviderFactory
import com.google.firebase.appcheck.recaptcha.RecaptchaAppCheckProviderFactory

private const val TAG = "AppCheckInit"

// App Check contract keys defined by the Firebase SDK and runtime harness.
private const val DEBUG_TOKEN_EXTRA = "FIREBASE_APPCHECK_DEBUG_TOKEN"
private const val DEBUG_STORE_PREFIX = "com.google.firebase.appcheck.debug.store."
private const val DEBUG_SECRET_KEY = "com.google.firebase.appcheck.debug.DEBUG_SECRET"
private const val RECAPTCHA_SITE_KEY_RES = "recaptcha_site_key"

// Local marker written ONLY when a registered debug token was explicitly injected by the harness Intent.
// Prevents a stale/auto-generated random UUID from earlier DebugAppCheckProviderFactory runs
// (or Android Auto Backup) from hijacking real-device sideloaded APKs.
private const val META_PREFS_NAME = "drst_appcheck_meta"
private const val META_HARNESS_TOKEN_VERIFIED = "harness_debug_token_verified"

object AppCheckRuntimeInfo {
    @Volatile
    var activeProvider: String = "uninitialized"
        internal set
}

/**
 * Configures Firebase App Check before any UI or Firebase AI operations.
 *
 * - AI Studio / emulator debug launches (Intent carries FIREBASE_APPCHECK_DEBUG_TOKEN):
 *   persists the token synchronously via commit() and installs DebugAppCheckProviderFactory.
 * - Real Android phones running sideloaded debug APKs (no harness debug token in Intent):
 *   clears any stale random DEBUG_SECRET and installs RecaptchaAppCheckProviderFactory using the
 *   provisioned Android reCAPTCHA Enterprise site key so Gemini AI works cleanly on physical devices.
 * - Release builds: always installs RecaptchaAppCheckProviderFactory.
 */
fun configureAppCheck(context: Context, intent: Intent?) {
    try {
        if (FirebaseApp.getApps(context).isEmpty()) {
            FirebaseApp.initializeApp(context)
        }

        val appCheck = FirebaseAppCheck.getInstance()
        val recaptchaSiteKey = resolveRecaptchaSiteKey(context)

        if (BuildConfig.DEBUG) {
            val intentDebugToken = intent?.getStringExtra(DEBUG_TOKEN_EXTRA)?.trim()
            val persistenceKey = FirebaseApp.getInstance().persistenceKey
            val debugStorePrefs = context.getSharedPreferences(
                "$DEBUG_STORE_PREFIX$persistenceKey",
                Context.MODE_PRIVATE
            )
            val metaPrefs = context.getSharedPreferences(META_PREFS_NAME, Context.MODE_PRIVATE)

            if (!intentDebugToken.isNullOrEmpty()) {
                // CRITICAL: MUST use synchronous commit() before DebugAppCheckProviderFactory reads it.
                debugStorePrefs.edit()
                    .putString(DEBUG_SECRET_KEY, intentDebugToken)
                    .commit()
                metaPrefs.edit()
                    .putBoolean(META_HARNESS_TOKEN_VERIFIED, true)
                    .commit()
                appCheck.installAppCheckProviderFactory(
                    DebugAppCheckProviderFactory.getInstance()
                )
                AppCheckRuntimeInfo.activeProvider = "debug-intent"
                Log.d(TAG, "App Check debug secret committed from Intent; DebugAppCheckProviderFactory installed.")
            } else {
                val hasVerifiedHarnessToken = metaPrefs.getBoolean(META_HARNESS_TOKEN_VERIFIED, false) &&
                    !debugStorePrefs.getString(DEBUG_SECRET_KEY, null).isNullOrBlank()

                if (hasVerifiedHarnessToken) {
                    appCheck.installAppCheckProviderFactory(
                        DebugAppCheckProviderFactory.getInstance()
                    )
                    AppCheckRuntimeInfo.activeProvider = "debug-harness-cached"
                    Log.d(TAG, "Using verified harness debug secret; DebugAppCheckProviderFactory installed.")
                } else if (!recaptchaSiteKey.isNullOrBlank()) {
                    // Real Android phone running sideloaded debug APK:
                    // Purge any stale random UUID previously auto-generated by DebugAppCheckProviderFactory
                    // and use real reCAPTCHA Enterprise attestation instead.
                    if (debugStorePrefs.contains(DEBUG_SECRET_KEY)) {
                        debugStorePrefs.edit().remove(DEBUG_SECRET_KEY).commit()
                    }
                    appCheck.installAppCheckProviderFactory(
                        RecaptchaAppCheckProviderFactory.getInstance(recaptchaSiteKey)
                    )
                    AppCheckRuntimeInfo.activeProvider = "recaptcha-device"
                    Log.d(TAG, "Real device detected (no harness debug token); RecaptchaAppCheckProviderFactory installed.")
                } else {
                    appCheck.installAppCheckProviderFactory(
                        DebugAppCheckProviderFactory.getInstance()
                    )
                    AppCheckRuntimeInfo.activeProvider = "debug-fallback"
                    Log.w(TAG, "No harness debug token or recaptcha_site_key found; falling back to DebugAppCheckProviderFactory.")
                }
            }
        } else {
            if (!recaptchaSiteKey.isNullOrBlank()) {
                appCheck.installAppCheckProviderFactory(
                    RecaptchaAppCheckProviderFactory.getInstance(recaptchaSiteKey)
                )
                AppCheckRuntimeInfo.activeProvider = "recaptcha-release"
                Log.d(TAG, "Release RecaptchaAppCheckProviderFactory installed.")
            } else {
                AppCheckRuntimeInfo.activeProvider = "missing-recaptcha-key"
                Log.e(TAG, "recaptcha_site_key string resource is missing or blank in release build.")
            }
        }
    } catch (e: Exception) {
        AppCheckRuntimeInfo.activeProvider = "error:${e.javaClass.simpleName}"
        Log.e(TAG, "Failed to initialize Firebase App Check", e)
    }
}

private fun resolveRecaptchaSiteKey(context: Context): String? {
    val resId = context.resources.getIdentifier(
        RECAPTCHA_SITE_KEY_RES,
        "string",
        context.packageName
    )
    if (resId == 0) return null
    return context.getString(resId).trim().takeIf { it.isNotEmpty() }
}
